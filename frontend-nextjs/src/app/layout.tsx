// interface payload JWT (không dùng `any`)
interface JwtPayload {
  displayName?: string;
  name?: string;
  sub?: string;
  [key: string]: unknown;
}

function decodeJwtServer(token: string | null): JwtPayload | null {
  if (!token) return null;
  try {
    const parts = token.split('.');
    if (parts.length < 2) return null;
    const payload = parts[1];

    // base64url -> base64, thêm padding nếu cần
    const base64 = payload.replace(/-/g, '+').replace(/_/g, '/');
    const padded = base64 + '='.repeat((4 - (base64.length % 4)) % 4);
    const buff = Buffer.from(padded, 'base64');
    const json = buff.toString('utf8');

    const parsed = JSON.parse(json) as JwtPayload;
    return parsed;
  } catch (e) {
    console.warn('decodeJwtServer error', e);
    return null;
  }
}

// NOTE: layout function is async because cookies() returns a Promise
export default async function RootLayout({ children }: { children: React.ReactNode }) {
  const cookieStore = await cookies();
  const token = cookieStore.get('access_token')?.value ?? null;
  const decoded = decodeJwtServer(token);

  const username =
    typeof decoded?.displayName === 'string' ? decoded.displayName :
    typeof decoded?.name === 'string' ? decoded.name :
    typeof decoded?.sub === 'string' ? decoded.sub :
    null;

  return (
    <html lang="en">
      <body
        className={`${geistSans.variable} ${geistMono.variable} antialiased`}
      >
        
        {children}
        
      </body>
    </html>
  );
}
